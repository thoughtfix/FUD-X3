#!/usr/bin/env python3
# Convert FUD's 135x135 Zuse PNG faces into 1-bit, upscaled, dithered bitmaps
# embedded as a C header for drawBitmap. Source art is FUD (thoughtfix's own);
# the generated header is committed so the build never needs other-repos/.
#
# Run from the repo root:  .venv/bin/python scripts/gen_faces.py
import os
from PIL import Image

SRC = "other-repos/FUD-Firmware/images"
OUT = "src/art/ZuseFaces.h"
ZUSE_SIZE = 240   # Zuse's own expression
ICON_SIZE = 150   # the threat icon shown beside him
SMALL_SIZE = 144  # the little corner mascot

# Zuse's reactions (his face) and the threat icons (shown beside him). gamma<1
# brightens the fill (keeping black outlines dark) so saturated fills like the
# red angry face don't dither to near-solid black.
ZUSE = [("happy", "defaultsmile", 0.9), ("wary", "neutralface", 0.9),
        ("angry", "redface", 0.45)]
ICONS = [("camera", "lord-nikon", 1.0), ("hacker", "acidburn", 1.0),
         ("attack", "zerocool", 1.0)]


def convert(name, size, gamma=1.0):
    im = Image.open(os.path.join(SRC, name + ".png")).convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    im = Image.alpha_composite(bg, im).convert("L")
    if gamma != 1.0:
        im = im.point(lambda p: int(255 * ((p / 255.0) ** gamma)))
    im = im.resize((size, size), Image.LANCZOS).convert("1")  # dither
    px = im.load()
    row_bytes = (size + 7) // 8
    data = bytearray()
    for y in range(size):
        for bx in range(row_bytes):
            b = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < size and px[x, y] == 0:  # black -> set bit (ink)
                    b |= (0x80 >> bit)
            data.append(b)
    return bytes(data)


def emit_array(lines, sym, data):
    lines.append(f"static const uint8_t {sym}[] = {{")
    row = []
    for b in data:
        row.append("0x%02x," % b)
        if len(row) == 16:
            lines.append("  " + "".join(row)); row = []
    if row:
        lines.append("  " + "".join(row))
    lines.append("};")
    lines.append("")


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    L = [
        "// AUTO-GENERATED by scripts/gen_faces.py. Do not edit.",
        "// 1-bit dithered art (set bit = black). Draw with drawBitmap.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"static constexpr int ZUSE_W = {ZUSE_SIZE};",
        f"static constexpr int ZUSE_H = {ZUSE_SIZE};",
        f"static constexpr int ICON_W = {ICON_SIZE};",
        f"static constexpr int ICON_H = {ICON_SIZE};",
        f"static constexpr int ZUSE_SMALL_W = {SMALL_SIZE};",
        f"static constexpr int ZUSE_SMALL_H = {SMALL_SIZE};",
        "",
    ]
    for i, (mood, fname, lt) in enumerate(ZUSE):
        emit_array(L, "zuse_" + mood, convert(fname, ZUSE_SIZE, lt))
    for i, (name, fname, lt) in enumerate(ICONS):
        emit_array(L, "icon_" + name, convert(fname, ICON_SIZE, lt))
    emit_array(L, "zuse_small", convert("defaultsmile", SMALL_SIZE, 0.9))
    emit_array(L, "zuse_sleep", convert("yawning-face", ZUSE_SIZE, 0.9))
    emit_array(L, "zuse_low", convert("sadface", ZUSE_SIZE, 0.9))

    L.append("static const uint8_t* const ZUSE_FACES[] = {" +
             ", ".join("zuse_" + m for m, _, _l in ZUSE) + "};")
    L.append("static const uint8_t* const ZUSE_ICONS[] = {" +
             ", ".join("icon_" + n for n, _, _l in ICONS) + "};")
    L.append("")
    for i, (m, _, _l) in enumerate(ZUSE):
        L.append(f"#define ZFACE_{m.upper()} {i}")
    for i, (n, _, _l) in enumerate(ICONS):
        L.append(f"#define ZICON_{n.upper()} {i}")
    L.append("")
    open(OUT, "w").write("\n".join(L))
    print(f"wrote {OUT} (Zuse {ZUSE_SIZE}px, icons {ICON_SIZE}px)")


main()
